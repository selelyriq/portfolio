import sharp from 'sharp';
import { readdir, writeFile, stat, readFile } from 'fs/promises';
import { join, extname } from 'path';

const ALBUMS_DIR = './public/images/albums';
const OUT_PROJECTS = './src/data/projects.ts';
const OUT_FEED = './src/data/galleryFeed.ts';
const IMAGE_EXTS = new Set(['.jpg', '.jpeg', '.png', '.webp']);

function toSlug(name) {
  return name.trim().toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

const albumNames = (await readdir(ALBUMS_DIR))
  .filter(async name => (await stat(join(ALBUMS_DIR, name))).isDirectory())
  .filter(name => !name.startsWith('.'));

// resolve which are actually directories
const albumDirs = [];
for (const name of albumNames) {
  const s = await stat(join(ALBUMS_DIR, name));
  if (s.isDirectory()) albumDirs.push(name);
}
albumDirs.sort();

const projects = [];
const feedEntries = [];
let feedCounter = 1;

for (const albumName of albumDirs) {
  const albumPath = join(ALBUMS_DIR, albumName);
  const title = albumName.trim();
  const slug = toSlug(albumName);

  let files = (await readdir(albumPath))
    .filter(f => IMAGE_EXTS.has(extname(f).toLowerCase()) && !f.startsWith('.'))
    .sort();

  if (files.length === 0) continue;

  // Honour cover.txt if present — move that file to index 0
  try {
    const cover = (await readFile(join(albumPath, 'cover.txt'), 'utf8')).trim();
    if (cover && files.includes(cover)) {
      files = [cover, ...files.filter(f => f !== cover)];
      console.log(`  cover → ${cover}`);
    }
  } catch { /* no cover.txt — fine */ }

  console.log(`${title} — ${files.length} images`);

  const images = [];

  for (let i = 0; i < files.length; i++) {
    const filename = files[i];
    const filePath = join(albumPath, filename);
    // src is relative to /public/images/
    const src = `albums/${albumName}/${filename}`;

    let width = 1920;
    let height = 1280;
    try {
      const meta = await sharp(filePath).metadata();
      width = meta.width ?? 1920;
      height = meta.height ?? 1280;
    } catch {
      console.warn(`  ! could not read dimensions: ${filename}`);
    }

    images.push({ id: `${slug}-${i + 1}`, src, alt: '', width, height });
    feedEntries.push({
      id: `feed-${feedCounter++}`,
      src,
      alt: '',
      width,
      height,
      projectId: slug,
      projectTitle: title,
    });
  }

  projects.push({ id: slug, title, slug, images });
}

// --- projects.ts ---
const projectsTs = `import { PortfolioData } from "@/types";

// Auto-generated by scripts/generate-gallery-data.mjs — do not edit manually.
export const portfolioData: PortfolioData = {
  projects: [
${projects.map(p => `    {
      id: "${p.id}",
      title: "${p.title}",
      slug: "${p.slug}",
      images: [
${p.images.map(img =>
  `        { id: "${img.id}", src: "${img.src}", alt: "${img.alt}", width: ${img.width}, height: ${img.height} },`
).join('\n')}
      ],
    },`).join('\n')}
  ],
};
`;

// --- galleryFeed.ts ---
const feedTs = `import { FlatImage } from "@/types";

// Auto-generated by scripts/generate-gallery-data.mjs — do not edit manually.
export const galleryFeed: FlatImage[] = [
${feedEntries.map(e =>
  `  { id: "${e.id}", src: "${e.src}", alt: "${e.alt}", width: ${e.width}, height: ${e.height}, projectId: "${e.projectId}", projectTitle: "${e.projectTitle}" },`
).join('\n')}
];
`;

await writeFile(OUT_PROJECTS, projectsTs);
await writeFile(OUT_FEED, feedTs);

console.log(`\nDone.`);
console.log(`  projects.ts   — ${projects.length} albums`);
console.log(`  galleryFeed.ts — ${feedEntries.length} photos`);
